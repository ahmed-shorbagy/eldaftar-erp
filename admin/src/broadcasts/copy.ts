export function segmentSummary(segment: BroadcastSegment, days: number | null, shopName: string | null): string {
  if (segment === 'expiring' && days !== null) return `اشتراكات سارية تنتهي خلال ${days} يومًا`
  if (segment === 'shop') return shopName ? `متجر: ${shopName}` : segmentLabel.shop
  return segmentLabel[segment]
}
